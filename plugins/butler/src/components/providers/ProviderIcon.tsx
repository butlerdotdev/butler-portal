export interface ProviderIconProps {
  type: string;
  /** Wrap in the console's 40px neutral-800 rounded tile. */
  tile?: boolean;
  className?: string;
}

export const ProviderIcon = ({ type, tile, className }: ProviderIconProps) => {
  const classes = useStyles();
  let logo;
  switch ((type || '').toLowerCase()) {
    case 'harvester':
      logo = <HarvesterLogo />;
      break;
    case 'nutanix':
      logo = <NutanixLogo />;
      break;
    case 'proxmox':
      logo = <ProxmoxLogo />;
      break;
    case 'aws':
      logo = <AwsLogo />;
      break;
    case 'azure':
      logo = <AzureLogo />;
      break;
    case 'gcp':
      logo = <GcpLogo />;
      break;
    default:
      logo = <ServerIcon className={classes.fallback} />;
  }
  return (
    <div className={clsx(classes.root, tile && classes.tile, className)}>
      {logo}
    </div>
  );
};
